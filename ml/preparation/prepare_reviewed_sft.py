#!/usr/bin/env python3
"""Prepare supervised fine-tuning samples ONLY from externally rights-reviewed data.

No fabricated medical training examples are generated by this program.
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

REQUIRED = {"scenario_id", "language", "prompt", "response", "source_id",
            "license", "rights_verified", "clinician_reviewed", "reviewed_by"}


def validate(row: dict) -> None:
    if missing := (REQUIRED - row.keys()):
        raise ValueError(f"Missing supervised data fields: {sorted(missing)}")
    if row["language"] not in {"en", "te"}:
        raise ValueError("This release is restricted to English/Telugu")
    if row["rights_verified"] is not True or row["clinician_reviewed"] is not True:
        raise ValueError("Rights and clinician review MUST both be explicitly approved")
    if not all(isinstance(row[key], str) and row[key].strip() for key in
               ("scenario_id", "prompt", "response", "source_id", "license", "reviewed_by")):
        raise ValueError("Incomplete reviewed example")
    if len(row["prompt"]) > 4000 or len(row["response"]) > 6000:
        raise ValueError("Training sample exceeds size bounds")


def split(rows: list[dict], seed: int = 42) -> tuple[list[dict], list[dict]]:
    for item in rows:
        validate(item)
    scenarios = sorted({row["scenario_id"] for row in rows})
    if len(scenarios) < 2:
        raise ValueError("Need at least two distinct scenarios for a held-out split")
    random.Random(seed).shuffle(scenarios)
    count = max(1, min(len(scenarios) - 1, round(0.2 * len(scenarios))))
    validation_ids = set(scenarios[:count])
    return (
        [r for r in rows if r["scenario_id"] not in validation_ids],
        [r for r in rows if r["scenario_id"] in validation_ids],
    )


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input", type=Path, required=True)
    p.add_argument("--output-dir", type=Path, required=True)
    p.add_argument("--seed", type=int, default=42)
    a = p.parse_args()
    records = [json.loads(line) for line in a.input.read_text(encoding="utf-8").splitlines() if line.strip()]
    train, validation = split(records, a.seed)
    a.output_dir.mkdir(parents=True, exist_ok=True)
    for name, rows in (("train", train), ("validation", validation)):
        output = a.output_dir / f"{name}.jsonl"
        if output.exists():
            raise FileExistsError(f"Refusing to overwrite {output}")
        output.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(json.dumps({"train": len(train), "validation": len(validation),
                      "scenario_leakage": False, "clinical_quality_claim": False}))


if __name__ == "__main__":
    main()
